export function errorMessage(error: any, status?: number): string {
  const code=typeof error==='string'?error:error?.response?.data?.error?.code||error?.code||error?.message;
  if(ERROR_MESSAGES[code])return ERROR_MESSAGES[code];
  const message=error?.response?.data?.error?.message||error?.message;
  if(!error?.code && typeof message==='string' && /[À-ỹ]/u.test(message))return message;
  const http=status||error?.response?.status||error?.status;
  if(http===401)return ERROR_MESSAGES.UNAUTHORIZED;
  if(http===402)return ERROR_MESSAGES.INSUFFICIENT_CREDIT;
  if(http===403)return ERROR_MESSAGES.FORBIDDEN;
  if(http===404)return ERROR_MESSAGES.NOT_FOUND;
  if(http===409)return 'Dữ liệu đã thay đổi. Vui lòng tải lại rồi thử lại.';
  if(http===429)return ERROR_MESSAGES.RATE_LIMIT_EXCEEDED;
  if(http>=500)return ERROR_MESSAGES.INTERNAL_ERROR;
  if(code==='ERR_NETWORK'||code==='ECONNABORTED'||code==='ETIMEDOUT'||code==='Failed to fetch')return 'Không kết nối được máy chủ. Vui lòng kiểm tra kết nối rồi thử lại.';
  return ERROR_MESSAGES.REQUEST_FAILED;
}
